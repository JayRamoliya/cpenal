// Security helper: ensure any requested path is strictly within USER_HOME_DIR
export function resolveSafePath(userRelativePath: string = ''): { safePath: string; displayPath: string; isAllowed: boolean } {
  // Normalize leading slash and strip out /home/demo if provided in user path
  let cleaned = userRelativePath.trim().replace(/\\/g, '/');
  
  if (cleaned.startsWith('/home/demo')) {
    cleaned = cleaned.replace(/^\/home\/demo/, '');
  }
  
  // Remove dangerous prefix sequences
  cleaned = cleaned.replace(/^\/+/, '');
  
  const absolutePath = path.resolve(USER_HOME_DIR, cleaned);
  
  // Security verification: check if absolutePath is inside or equal to USER_HOME_DIR
  const isAllowed = absolutePath === USER_HOME_DIR || absolutePath.startsWith(USER_HOME_DIR + path.sep);
  
  const relativeFromHome = path.relative(USER_HOME_DIR, absolutePath).replace(/\\/g, '/');
  const displayPath = '/home/demo' + (relativeFromHome ? '/' + relativeFromHome : '');

  return {
    safePath: absolutePath,
    displayPath,
    isAllowed,
  };
}

